package main

// ========================================================================
// ИМПОРТЫ
// ========================================================================
// import "..." — подключение внешней библиотеки.
// github.com/gdamore/tcell/v2 — кроссплатформенная библиотека для работы с терминалом.
//
// Что умеет tcell:
//   - Рисовать символы в любой позиции экрана (не только последовательно)
//   - Обрабатывать нажатия клавиш (включая стрелки, Esc, F1-F12)
//   - Управлять цветами текста и фона
//   - Отслеживать изменение размера окна терминала
//   - Работать на Windows, Linux, macOS
//
// ВАЖНО: используем v2, а не v3. Версия v3 нестабильна и может вызвать ошибки компиляции.
import "github.com/gdamore/tcell/v2"

// ========================================================================
// ОПРЕДЕЛЕНИЕ ТИПА Sprite
// ========================================================================
// type Sprite struct { ... } — объявление новой структуры (типа данных).
//
// Структура в Go — это набор полей, объединённых под одним именем.
// Аналог класса в Java/C++, но без методов внутри (методы объявляются отдельно).
//
// Sprite — базовый объект игры. Представляет любой элемент, который можно отрисовать:
// игрока ('@'), монету ('0'), врага ('X').
type Sprite struct {
	// Char rune — символ, который будет отображаться на экране.
	//
	// rune — это тип данных для одного Unicode-символа.
	// В Go rune = int32 (4 байта), что позволяет хранить любой символ Unicode.
	// Примеры: '@', '0', 'X', '♥', '─', '┌'.
	//
	// Почему rune, а не string?
	//   - rune — один символ (4 байта)
	//   - string — последовательность символов (переменная длина)
	// Для отрисовки одного символа нужен именно rune.
	Char rune

	// X, Y int — координаты объекта на экране.
	//
	// int — целое число (размер зависит от архитектуры: 32 или 64 бита).
	// X — горизонтальная позиция (столбец), Y — вертикальная (строка).
	//
	// В терминале отсчёт идёт от левого верхнего угла:
	//   (0, 0) — верхний левый угол
	//   (X увеличивается вправо, Y увеличивается вниз)
	//
	// Пример: если X=10, Y=5, символ будет в 11-м столбце, 6-й строке.
	X, Y int

	// Style tcell.Style — стиль отображения символа.
	//
	// tcell.Style — структура из библиотеки tcell, хранящая:
	//   - Цвет переднего плана (Foreground)
	//   - Цвет фона (Background)
	//   - Атрибуты (жирный, подчёркнутый, мигающий и т.д.)
	//
	// Если стиль не задан, используется tcell.StyleDefault (белый на чёрном).
	//
	// Пример создания стиля с зелёным цветом:
	//   style := tcell.StyleDefault.Foreground(tcell.ColorGreen)
	Style tcell.Style
}

// ========================================================================
// КОНСТРУКТОР NewSprite
// ========================================================================
// func NewSprite(...) *Sprite — функция-конструктор.
//
// В Go нет специального синтаксиса конструкторов (как в Java/C++).
// Вместо этого используют функции вида NewXxx(), которые создают и возвращают объект.
//
// Параметры:
//   - char rune — символ для отображения (например, '@')
//   - x, y int — начальные координаты на экране
//
// Возвращает: *Sprite — указатель на созданный объект.
//
// Почему указатель (*Sprite), а не просто Sprite?
//   1. Эффективность: передача указателя (8 байт) быстрее, чем копирование всей структуры.
//   2. Изменяемость: через указатель можно изменять объект в разных частях программы.
//   3. Идентичность: все ссылки на один объект указывают на одну область памяти.
func NewSprite(char rune, x, y int) *Sprite {
	// return &Sprite{...} — создаём новый объект и возвращаем указатель на него.
	//
	// & — оператор взятия адреса. Создаёт указатель на объект.
	//
	// Внутри фигурных скобок — инициализация полей:
	//   Char: char — поле Char получает значение параметра char
	//   X: x — поле X получает значение параметра x
	//   Y: y — поле Y получает значение параметра y
	//   Style: tcell.StyleDefault — стандартный стиль (белый на чёрном)
	//
	// Если поле не указано, оно получает нулевое значение:
	//   - int → 0
	//   - rune → 0 (нулевой символ)
	//   - bool → false
	//   - указатель → nil
	return &Sprite{
		Char:  char,
		X:     x,
		Y:     y,
		Style: tcell.StyleDefault,
	}
}

// ========================================================================
// МЕТОД Draw
// ========================================================================
// func (s *Sprite) Draw(screen tcell.Screen) — метод структуры Sprite.
//
// (s *Sprite) — это "получатель" метода (receiver).
// Означает, что метод вызывается для конкретного объекта Sprite.
//
// s — это переменная, через которую обращаемся к полям объекта.
// Аналог this в Java/C++ или self в Python.
//
// *Sprite — получатель-указатель. Позволяет изменять объект внутри метода.
// Если бы было просто Sprite (без *), метод работал бы с копией объекта.
//
// Параметр:
//   - screen tcell.Screen — экран терминала (интерфейс).
//     tcell.Screen — абстракция над терминалом. Представляет весь экран как холст.
//
// Пример вызова:
//   player := NewSprite('@', 10, 5)
//   player.Draw(screen) // Рисуем игрока в позиции (10, 5)
func (s *Sprite) Draw(screen tcell.Screen) {
	// screen.SetContent(...) — метод tcell, рисующий один символ в заданной позиции.
	//
	// Параметры метода SetContent:
	//   1. s.X — координата X (столбец)
	//   2. s.Y — координата Y (строка)
	//   3. s.Char — символ для отрисовки (rune)
	//   4. nil — комбинированный символ (combining character).
	//            Используется для диакритических знаков (например, акценты в французском).
	//            nil означает, что мы не используем такие символы.
	//   5. s.Style — стиль отображения (цвет, фон, атрибуты)
	//
	// Пример:
	//   screen.SetContent(10, 5, '@', nil, tcell.StyleDefault.Foreground(tcell.ColorGreen))
	//   → Рисует зелёный символ '@' в позиции (10, 5)
	//
	// ВАЖНО: этот метод только добавляет символ в буфер экрана.
	// Реальное отображение на терминале происходит после вызова screen.Show().
	// Это отложенная отрисовка — защита от мерцания экрана.
	screen.SetContent(
		s.X,
		s.Y,
		s.Char,
		nil,
		s.Style,
	)
}

// ========================================================================
// КЛЮЧЕВЫЕ КОНЦЕПЦИИ GO В ЭТОМ ФАЙЛЕ
// ========================================================================
//
// 1. СТРУКТУРЫ (struct)
//    - Способ группировки связанных данных
//    - Аналог класса без методов
//    - Пример: type Sprite struct { Char rune; X, Y int; Style tcell.Style }
//
// 2. УКАЗАТЕЛИ (*Type)
//    - Ссылка на объект в памяти
//    - Позволяют изменять объект без копирования
//    - Оператор & создаёт указатель: &Sprite{...}
//    - Оператор * извлекает значение из указателя (в нашем случае не используется)
//
// 3. МЕТОДЫ
//    - Функции, привязанные к типу
//    - Объявляются с получателем: func (s *Sprite) Draw(...)
//    - Вызываются через точку: sprite.Draw(screen)
//
// 4. КОНСТРУКТОРЫ
//    - В Go нет специального синтаксиса
//    - Используют функции NewXxx()
//    - Возвращают указатель на созданный объект
//
// 5. RUNE VS STRING
//    - rune — один символ (4 байта, int32)
//    - string — последовательность символов (переменная длина)
//    - Для отрисовки одного символа нужен rune
//    - Литерал rune: 'A' (одинарные кавычки)
//    - Литерал string: "A" (двойные кавычки)
//
// 6. ИНТЕРФЕЙСЫ
//    - tcell.Screen — интерфейс, скрывающий конкретную реализацию терминала
//    - Позволяет писать код, не зависящий от конкретного терминала