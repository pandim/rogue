// Каждый метод проверяет три условия перед воспроизведением:
//   1. Динамик инициализирован (иначе звук невозможен)
//   2. Звуковые эффекты включены (клавиша N)
//   3. Буфер не пустой (звук был успешно загружен из файла)
//
// Если хотя бы одно условие не выполнено — метод тихо возвращается.
// Это защищает от ошибок и позволяет игре работать без звука.

// PlayCoin — звук сбора монеты.
// Вызывается в main.go при сборе любой монеты (обычной, золотой, редкой)
// и при подборе бонуса-сердечка.
func (sm *SoundManager) PlayCoin() {
	// Проверка трёх условий через оператор "или":
	// если хотя бы одно истинно — выходим без воспроизведения
	if !sm.initialized || !sm.soundEnabled || sm.coinBuffer.Len() == 0 {
		return
	}

	// Создаём новый стример из буфера и запускаем его.
	//
	// ВАЖНО: каждый вызов создаёт НОВЫЙ стример из буфера.
	// Это позволяет звукам накладываться друг на друга:
	// если игрок быстро соберёт несколько монет подряд,
	// каждый звук будет воспроизведён отдельно, не прерывая предыдущий.
	//
	// Если бы мы хранили один стример и перезапускали его,
	// звуки бы прерывали друг друга.
	speaker.Play(sm.coinBuffer.Streamer(0, sm.coinBuffer.Len()))
}

