// РЕГУЛИРОВКА ГРОМКОСТИ
// ========================================================================
// Громкость регулируется клавишами:
//   - '-' или '_' — уменьшить на 1 уровень
//   - '=' или '+' — увеличить на 1 уровень
//
// Диапазон: от 1 до 16 (отображается как 0.5 .. 8.0)
// Шаг: 1 уровень (0.5 в отображении)
//
// ВАЖНО: громкость меняется М МГНОВЕННО, без пересоздания контроллера.
// Просто присваивается новое значение полю Volume существующего эффекта.
// Это решает проблему зависания игры, которая возникала при
// пересоздании контроллера на каждое нажатие клавиши.

// VolumeUp — увеличивает громкость на 1 уровень (+0.5 в отображении).
// Вызывается при нажатии клавиши '=' или '+'.
func (sm *SoundManager) VolumeUp() {
	// Проверка: динамик инициализирован и эффект громкости существует
	if !sm.initialized || sm.musicVolumeEffect == nil {
		return
	}

	// Проверка максимума: если уже на максимуме, не увеличиваем
	if sm.volumeLevel >= maxVolumeLevel {
		log.Println("[Sound] 🔊 Громкость уже на максимуме (8.0)")
		return
	}

	// Увеличиваем уровень на 1.
	// Оператор "++" эквивалентен записи "sm.volumeLevel = sm.volumeLevel + 1"
	sm.volumeLevel++

	// Просто меняем поле Volume у существующего эффекта — без пересоздания.
	// Изменение применяется мгновенно: следующий считанный сэмпл
	// уже будет воспроизведён с новой громкостью.
	//
	// Это ключевое решение, устраняющее зависание игры при регулировке громкости.
	sm.musicVolumeEffect.Volume = sm.getRealVolume()

	// Логируем новое значение громкости и уровень
	log.Printf("[Sound] 🔊 Громкость: %.1f (уровень %d/%d)",
		sm.GetDisplayVolume(), sm.volumeLevel, maxVolumeLevel)
}

// VolumeDown — уменьшает громкость на 1 уровень (-0.5 в отображении).
// Вызывается при нажатии клавиши '-' или '_'.
// Логика зеркальна методу VolumeUp.
func (sm *SoundManager) VolumeDown() {
	// Проверка: динамик инициализирован и эффект громкости существует
	if !sm.initialized || sm.musicVolumeEffect == nil {
		return
	}

	// Проверка минимума: если уже на минимуме, не уменьшаем
	if sm.volumeLevel <= minVolumeLevel {
		log.Println("[Sound] 🔉 Громкость уже на минимуме (0.5)")
		return
	}

	// Уменьшаем уровень на 1.
	// Оператор "--" эквивалентен записи "sm.volumeLevel = sm.volumeLevel - 1"
	sm.volumeLevel--

	// Мгновенно меняем громкость без пересоздания контроллера
	sm.musicVolumeEffect.Volume = sm.getRealVolume()

	// Логируем новое значение громкости и уровень
	log.Printf("[Sound] 🔉 Громкость: %.1f (уровень %d/%d)",
		sm.GetDisplayVolume(), sm.volumeLevel, maxVolumeLevel)
}

