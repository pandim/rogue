// ToggleMusic — переключает состояние музыки (вкл/выкл).
// Вызывается при нажатии клавиши M.
//
// Реализация через паузу (а не удаление стримера):
//   - При выключении: ставим музыку на паузу
//   - При включении: снимаем с паузы
//   - Музыка продолжает играть с того же места, где остановилась
//
// Это более эффективно, чем удаление и повторное создание стримера:
//   - Нет утечек памяти
//   - Нет задержки на повторное декодирование
//   - Музыка возобновляется с той же позиции
func (sm *SoundManager) ToggleMusic() {
	// Проверка: динамик инициализирован и музыка была загружена
	if !sm.initialized || sm.musicLoop == nil {
		return
	}

	// Инвертируем флаг: истина → ложь, ложь → истина
	sm.musicEnabled = !sm.musicEnabled

	// speaker.Lock() — блокирует динамик для безопасного изменения стримеров.
	//
	// Зачем нужна блокировка?
	// Динамик работает в отдельной горутине и постоянно читает данные
	// из стримеров. Если менять состояние стримера без блокировки,
	// может произойти состояние гонки — одновременное чтение и запись,
	// что приводит к ошибкам воспроизведения или панике.
	//
	// Блокировка гарантирует, что динамик "увидит" изменение атомарно.
	speaker.Lock()
	if sm.musicCtrl != nil {
		// Устанавливаем паузу в противоположное значение от флага:
		//   - Музыка включена (флаг истина) → пауза ложь → играет
		//   - Музыка выключена (флаг ложь) → пауза истина → стоит
		sm.musicCtrl.Paused = !sm.musicEnabled
	}
	// Разблокируем динамик
	speaker.Unlock()

	// Логируем новое состояние музыки
	if sm.musicEnabled {
		log.Printf("[Sound] Музыка: ВКЛ (громкость: %.1f)", sm.GetDisplayVolume())
	} else {
		log.Println("[Sound] Музыка: ВЫКЛ")
	}
}

// ToggleSound — переключает состояние звуковых эффектов.
// Вызывается при нажатии клавиши N.
//
// В отличие от музыки, здесь не нужна блокировка динамика:
// звуковые эффекты не имеют постоянного стримера — они создаются
// заново при каждом вызове Play. Флаг проверяется в момент вызова.
//
// Фоновая музыка не затрагивается этим переключателем:
// она управляется отдельно клавишей M.
func (sm *SoundManager) ToggleSound() {
	sm.soundEnabled = !sm.soundEnabled
}

