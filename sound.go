// Close — очищает динамик при выходе из игры.
// Вызывается через отложенный вызов в main.go: "defer sound.Close()"
//
// Что делает метод:
//   1. Останавливает все активные воспроизведения
//   2. Закрывает звуковое устройство, освобождая ресурсы
//
// Без вызова этого метода звуковое устройство могло бы остаться
// заблокированным, и другие программы не смогли бы его использовать
// до завершения процесса.
func (sm *SoundManager) Close() {
	// Проверяем, что динамик был инициализирован.
	// Если инициализация не удалась при создании, закрывать нечего.
	if sm.initialized {
		// speaker.Clear() — останавливает все активные воспроизведения
		// и очищает очередь стримеров.
		speaker.Clear()

		// speaker.Close() — закрывает устройство вывода звука,
		// освобождая системные ресурсы.
		// После этого вызова динамик больше не может воспроизводить звук.
		speaker.Close()
	}
}