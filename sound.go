// ========================================================================
// КОНСТАНТЫ ГРОМКОСТИ
// ========================================================================
// Громкость задаётся УРОВНЕМ от 1 до 16.
// Отображается как значение от 0.5 до 8.0 с шагом 0.5.
// Реальный Volume вычисляется по формуле: level * 0.5 - 4.5
//
// Зачем такая схема?
//   - Пользователю понятнее "громкость 3.5", чем "параметр Volume = -1.0"
//   - Шаг 0.5 даёт 16 уровней — достаточно для точной настройки
//   - Формула преобразует уровень в реальный множитель громкости
//
// Таблица соответствия:
//   Уровень 1  → отображение 0.5 → Volume = -4.0 → множитель ~0.06 (очень тихо)
//   Уровень 7  → отображение 3.5 → Volume = -1.0 → множитель 0.5  (вдвое тише оригинала)
//   Уровень 9  → отображение 4.5 → Volume = 0.0  → множитель 1.0  (оригинал)
//   Уровень 16 → отображение 8.0 → Volume = 3.5  → множитель ~11.3 (очень громко)
const (
	minVolumeLevel     = 1  // минимальный уровень (отображается как 0.5)
	maxVolumeLevel     = 16 // максимальный уровень (отображается как 8.0)
	defaultVolumeLevel = 7  // начальный уровень (отображается как 3.5, Volume = -1.0)
)

// ========================================================================
// СТРУКТУРА SoundManager
// ========================================================================
// SoundManager — центральный класс для управления всем звуком в игре.
// Инкапсулирует всю логику загрузки, воспроизведения и управления звуками.
//
// Почему отдельная структура, а не глобальные функции?
//   1. Инкапсуляция: все данные и методы в одном месте
//   2. Состояние: можно хранить настройки (включена/выключена музыка, громкость)
//   3. Тестируемость: можно создать несколько экземпляров для тестов
//   4. Чистота кода: sound.PlayCoin() понятнее, чем PlayCoinSound()
type SoundManager struct {
	// initialized bool — флаг, показывающий, удалось ли инициализировать динамик.
	// Если false, все методы будут "молчать" и не вызывать ошибок.
	// Это позволяет игре работать без звука, если звуковая карта недоступна.
	// Защита от сбоев: пользователь без звуковой карты всё равно сможет играть.
	initialized bool

	// musicEnabled bool — включена ли фоновая музыка.
	// Управляется клавишей M.
	// Если false, музыка ставится на паузу, но не удаляется из очереди.
	// При повторном включении музыка продолжит играть с того же места.
	musicEnabled bool

	// soundEnabled bool — включены ли звуковые эффекты.
	// Управляется клавишей N.
	// Если false, методы PlayCoin/PlayHit/PlayLevelUp просто возвращаются,
	// не воспроизводя звук. Фоновая музыка при этом продолжает играть.
	soundEnabled bool

	// musicCtrl *beep.Ctrl — указатель на контроллер музыки.
	// beep.Ctrl — обёртка над стримером, позволяющая ставить воспроизведение на паузу.
	// Поле Paused управляет состоянием: true = пауза, false = воспроизведение.
	// Хранится указатель, чтобы менять состояние без пересоздания стримера.
	musicCtrl *beep.Ctrl

	// musicLoop beep.Streamer — зацикленный стример музыки.
	// Сохраняется отдельно от musicCtrl, чтобы его можно было переиспользовать.
	// beep.Streamer — интерфейс для потока аудио-данных.
	// Этот поток бесконечный (обёрнут в beep.Loop), поэтому не исчерпывается.
	musicLoop beep.Streamer

	// musicVolumeEffect *effects.Volume — указатель на эффект громкости.
	//
	// ВАЖНО: сохраняем указатель для БЫСТРОЙ смены громкости без пересоздания
	// контроллера. Это решает проблему зависания игры при регулировке громкости.
	//
	// Раньше при каждом изменении громкости создавался новый контроллер,
	// что приводило к утечке стримеров и зависанию. Теперь просто меняем
	// поле Volume у существующего эффекта — мгновенно и безопасно.
	musicVolumeEffect *effects.Volume

	// coinBuffer *beep.Buffer — буфер со звуком сбора монеты.
	// beep.Buffer хранит все сэмплы в памяти, что позволяет воспроизводить звук
	// многократно без повторной загрузки из файла.
	//
	// Почему буфер, а не поток из файла?
	//   1. Быстрее: не нужно читать файл при каждом воспроизведении
	//   2. Можно воспроизводить звук многократно одновременно
	//      (например, при быстром сборе нескольких монет подряд)
	//   3. Нет задержек на чтение с диска
	coinBuffer *beep.Buffer

	// hitBuffer *beep.Buffer — буфер со звуком столкновения с врагом.
	// Воспроизводится при потере жизни.
	hitBuffer *beep.Buffer

	// levelBuffer *beep.Buffer — буфер со звуком перехода на новый уровень.
	// Воспроизводится, когда все монеты собраны.
	levelBuffer *beep.Buffer

	// volumeLevel int — текущий уровень громкости (от 1 до 16).
	// Отображается в UI как значение от 0.5 до 8.0.
	// Регулируется клавишами '-' (уменьшить) и '=' (увеличить).
	// Шаг регулировки: 1 уровень (0.5 в отображении).
	volumeLevel int
}

// ========================================================================
// КОНСТРУКТОР NewSoundManager
// ========================================================================
// Создаёт и инициализирует звуковой движок.
//
// Параметр:
//   - soundsDir string — путь к папке со звуковыми файлами (например, "sounds")
//
// Возвращает: *SoundManager — указатель на созданный объект.
//
// Что делает конструктор:
//   1. Создаёт объект с настройками по умолчанию
//   2. Инициализирует динамик (speaker.Init)
//   3. Создаёт буферы для звуковых эффектов
//   4. Загружает звуковые файлы в буферы
//
// Конструктор НЕ завершает программу при ошибках звука.
// Если звуковое устройство недоступно, игра продолжит работать без звука.
func NewSoundManager(soundsDir string) *SoundManager {
	// Создаём объект с начальными значениями:
	//   - музыка включена по умолчанию (истина)
	//   - звуки включены по умолчанию (истина)
	//   - громкость = 7 (отображается как 3.5, вдвое тише оригинала)
	//
	// Остальные поля получают нулевые значения автоматически:
	//   - указатели = nil
	//   - initialized = false (установится ниже при успешной инициализации)
	sm := &SoundManager{
		musicEnabled: true,
		soundEnabled: true,
		volumeLevel:  defaultVolumeLevel,
	}

	// === ИНИЦИАЛИЗАЦИЯ ДИНАМИКА ===
	// speaker.Init(44100, 44100/5) — инициализирует систему вывода звука.
	//
	// Параметры:
	//   - 44100 — частота дискретизации (sample rate) в герцах.
	//     44100 Гц — стандарт CD-качества, поддерживает весь слышимый
	//     диапазон частот (20 Гц - 20 кГц), воспринимаемый человеческим ухом.
	//   - 44100/5 = 8820 — размер буфера в сэмплах.
	//     Это примерно 200 мс звука (8820 / 44100 ≈ 0.2 сек).
	//
	// Компромисс размера буфера:
	//   - Больший буфер = стабильнее воспроизведение, но выше задержка
	//   - Меньший буфер = ниже задержка, но возможны заикания на слабых машинах
	//   - 200 мс — оптимальный баланс для игры
	//
	// Возвращает:
	//   - err — ошибка, если не удалось открыть звуковое устройство
	//     (например, нет звуковой карты, устройство занято другим процессом)
	err := speaker.Init(44100, 44100/5)
	if err != nil {
		// Если инициализация не удалась (например, нет звуковой карты),
		// логируем ошибку и возвращаем объект без звука.
		// Поле initialized остаётся ложным — все методы звука будут молчать.
		// Игра продолжит работать, просто без звука.
		log.Printf("[Sound] Не удалось инициализировать динамик: %v", err)
		log.Printf("[Sound] Игра будет работать без звука.")
		return sm
	}

	// Инициализация прошла успешно — устанавливаем флаг
	sm.initialized = true
	log.Println("[Sound] Динамик успешно инициализирован (44100 Гц, буфер 200мс)")

	// === СОЗДАНИЕ БУФЕРОВ ДЛЯ ЗВУКОВЫХ ЭФФЕКТОВ ===
	// beep.Format описывает формат аудио:
	//   - SampleRate: 44100 — частота дискретизации (должна совпадать с динамиком)
	//   - NumChannels: 2 — стерео (2 канала: левый и правый)
	//   - Precision: 2 — 2 байта на сэмпл (16 бит) — стандартное качество
	//
	// Формат буфера определяет, как будут интерпретироваться хранящиеся в нём данные.
	// Если формат буфера не совпадает с форматом динамика, потребуется ресемплинг.
	format := beep.Format{SampleRate: 44100, NumChannels: 2, Precision: 2}

	// Создаём три пустых буфера для трёх звуковых эффектов.
	// beep.NewBuffer(format) — создаёт буфер с указанным форматом.
	// Изначально буферы пустые — данные в них будут загружены ниже.
	sm.coinBuffer = beep.NewBuffer(format)  // Звук сбора монеты
	sm.hitBuffer = beep.NewBuffer(format)   // Звук удара врага
	sm.levelBuffer = beep.NewBuffer(format) // Звук нового уровня

	// === ЗАГРУЗКА ЗВУКОВЫХ ФАЙЛОВ ===
	// Загружаем каждый WAV-файл в соответствующий буфер.
	// Если файла нет, метод loadWAV молча пропустит его и запишет в лог.
	// Игра продолжит работать без отсутствующих звуков.
	//
	// Файлы должны находиться в папке, указанной в параметре soundsDir:
	//   sounds/coin.wav    — звук сбора монеты (короткий, приятный)
	//   sounds/hit.wav     — звук удара (неприятный, сигнализирующий об опасности)
	//   sounds/levelup.wav — звук нового уровня (радостная мелодия)
	sm.loadWAV(soundsDir+"/coin.wav", sm.coinBuffer)
	sm.loadWAV(soundsDir+"/hit.wav", sm.hitBuffer)
	sm.loadWAV(soundsDir+"/levelup.wav", sm.levelBuffer)

	return sm
}

// ========================================================================
// МЕТОД loadWAV
// ========================================================================
// Загружает WAV-файл в буфер.
//
// Параметры:
//   - path string — путь к файлу (например, "sounds/coin.wav")
//   - buffer *beep.Buffer — буфер, в который будут загружены данные
//
// Что делает метод:
//   1. Открывает файл
//   2. Декодирует WAV в поток сэмплов
//   3. Ресемплирует (если нужно) до 44100 Гц
//   4. Добавляет все сэмплы в буфер
//
// Обработка ошибок: метод не прерывает работу программы при ошибках.
// Если файл отсутствует или повреждён, буфер останется пустым,
// и звук просто не будет воспроизводиться.
func (sm *SoundManager) loadWAV(path string, buffer *beep.Buffer) {
	// Если динамик не инициализирован, просто выходим.
	// Проверка защищает от ошибок при работе без звуковой карты.
	if !sm.initialized {
		return
	}

	// os.Open(path) — открываем файл для чтения.
	// Возвращает:
	//   - f — файловый дескриптор (если успешно)
	//   - err — ошибка (если файла нет, нет прав и т.д.)
	f, err := os.Open(path)
	if err != nil {
		// Если файла нет (или другая ошибка), логируем и выходим.
		// Игра продолжит работать без этого звука.
		// Это не критическая ошибка — отсутствие звуковых файлов допустимо.
		log.Printf("[Sound] Файл не найден: %s (звук отключён)", path)
		return
	}

	// defer f.Close() — гарантированно закроем файл после выхода из функции.
	// defer выполняется в самом конце, даже если функция завершится с ошибкой.
	// Это предотвращает утечки файловых дескрипторов.
	//
	// Без defer файл остался бы открытым, и при большом количестве
	// таких утечек программа могла бы исчерпать лимит открытых файлов.
	defer f.Close()

	// wav.Decode(f) — декодируем WAV-файл в поток сэмплов.
	//
	// Возвращает:
	//   - streamer beep.StreamSeeker — поток сэмплов (можно читать и перематывать)
	//   - format beep.Format — формат аудио (частота, каналы)
	//   - err error — ошибка, если файл повреждён или имеет неверный формат
	//
	// Декодирование читает заголовок WAV-файла и подготавливает поток
	// для последовательного чтения сэмплов.
	streamer, format, err := wav.Decode(f)
	if err != nil {
		log.Printf("[Sound] Ошибка декодирования %s: %v", path, err)
		return
	}

	// === РЕСЕМПЛИНГ ===
	// beep.Resample(4, format.SampleRate, 44100, streamer) — изменяет частоту дискретизации.
	//
	// Параметры:
	//   - 4 — качество ресемплинга (1-4, где 4 — наилучшее, но медленнее).
	//     Качество 4 даёт минимальные искажения при преобразовании.
	//   - format.SampleRate — исходная частота (из файла, например, 22050 Гц)
	//   - 44100 — целевая частота (наша, чтобы соответствовать динамику)
	//   - streamer — исходный поток
	//
	// Зачем нужен ресемплинг?
	//   Если файл записан в 22050 Гц, а динамик работает на 44100 Гц,
	//   нужно преобразовать частоту, чтобы звук воспроизводился корректно.
	//   Без ресемплинга звук был бы искажён (слишком быстрый или медленный).
	//
	// Если частоты совпадают, ресемплинг всё равно создаётся, но работает
	// как прозрачная обёртка без реального преобразования.
	resampled := beep.Resample(4, format.SampleRate, 44100, streamer)

	// buffer.Append(resampled) — добавляем все сэмплы из потока в буфер.
	// Метод "высасывает" весь поток до конца, заполняя буфер.
	// После этого буфер содержит все данные звука в памяти.
	//
	// ВАЖНО: после вызова Append исходный поток полностью исчерпан.
	// Его нельзя использовать повторно — нужно создавать новый из буфера.
	buffer.Append(resampled)
	log.Printf("[Sound] Загружен: %s", path)
}

// ========================================================================
// МЕТОД getRealVolume (внутренний)
// ========================================================================
// Вычисляет реальный Volume для effects.Volume по текущему уровню громкости.
//
// Формула: level * 0.5 - 4.5
//
// Примеры:
//   - level = 1  → Volume = -4.0  (множитель x0.06, очень тихо)
//   - level = 7  → Volume = -1.0  (множитель x0.5, в 2 раза тише оригинала)
//   - level = 9  → Volume = 0.0   (множитель x1.0, оригинальная громкость)
//   - level = 16 → Volume = 3.5   (множитель x11.3, очень громко)
//
// Как работает effects.Volume:
//   Итоговая громкость = Base ^ Volume = 2 ^ Volume
//   Поэтому отрицательные значения уменьшают громкость,
//   а положительные — увеличивают.
//
// Возвращает: float64 — значение Volume для effects.Volume
//
// Метод приватный (начинается с маленькой буквы) — используется только
// внутри SoundManager. Внешний код использует GetDisplayVolume.
func (sm *SoundManager) getRealVolume() float64 {
	return float64(sm.volumeLevel)*0.5 - 4.5
}

// ========================================================================
// МЕТОД GetDisplayVolume
// ========================================================================
// Возвращает значение для отображения в UI (0.5 .. 8.0).
//
// Формула: level * 0.5
//
// Примеры:
//   - level = 1  → 0.5
//   - level = 7  → 3.5
//   - level = 16 → 8.0
//
// Возвращает: float64 — значение для отображения
//
// Метод публичный (начинается с большой буквы) — используется в main.go
// для отрисовки индикатора громкости в интерфейсе.
func (sm *SoundManager) GetDisplayVolume() float64 {
	return float64(sm.volumeLevel) * 0.5
}

